function result=verify_bridge_equivalence(outputRoot,baselineApi,runName)
% Necessary old/candidate bridge comparison, using frozen generated algorithms.
assert(batchStartupOptionUsed,'Use dedicated MATLAB batch via MCP.');
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
prepared=fullfile(root,'.runtime','ax02c2','prepared_04');
adapterPrepared=fullfile(root,'.runtime','ax02c2','adapter_native_01');
runtime=fullfile(root,'.runtime','ax02a','target','codegen','AXU5EV_R5_Runtime_ert_rtw');
adapter=fullfile(adapterPrepared,'adapter_01','codegen','AX02C2_Adapter_ert_rtw');
if nargin<3,runName='runtime_bridge_01';end
% First execute the existing verify_adapter contract in adapter_check_01.
% Reuse its completed PASS here; do not repeat the passed model comparison.
adapterResult=jsondecode(fileread(fullfile(outputRoot,'adapter_check_01','result.json')));
assert(strcmp(adapterResult.status,'ADAPTER_MODEL_C_PASS'));
out=fullfile(outputRoot,runName);assert(~isfolder(out));mkdir(out);
sources=dir(fullfile(runtime,'*.c'));sources=sources(~strcmp({sources.name},'ert_main.c'));
runtimeNames={sources.name};sources=fullfile(runtime,runtimeNames);
additional=dir(fullfile(adapter,'*.c'));
additional=additional(~ismember({additional.name},[runtimeNames,{'ert_main.c'}]));
sources=[sources,fullfile(adapter,{additional.name})];
sources=[sources,{fullfile(root,'integration','r5_host','ax01b_r5_bridge.c'), ...
 fullfile(root,'verification','ax02c2','perf_fix_01','runtime_bridge_access.c'), ...
 fullfile(root,'verification','ax02c2','perf_fix_01','runtime_bridge_probe_mex.c')}];
flags={'-R2018a','CFLAGS=$CFLAGS -O2 -fno-fast-math -ffp-contract=off', ...
 ['-I' runtime],['-I' adapter],['-I' fullfile(root,'integration','r5_host')], ...
 ['-I' fullfile(root,'integration','ax02c2_adapter')]};
mex(flags{:},'-DPERF_BASELINE',baselineApi,sources{:},'-outdir',out,'-output','ax02c2_bridge_baseline');
mex(flags{:},fullfile(root,'integration','ax02c2_adapter','ax02c2_adapter_api.c'),sources{:}, ...
 '-outdir',out,'-output','ax02c2_bridge_candidate');
addpath(out);
data=load(fullfile(prepared,'data','current_motion','reference.mat'),'u','feedback');
[oldRuntime,oldWords]=ax02c2_bridge_baseline(data.u,data.feedback);
[newRuntime,newWords]=ax02c2_bridge_candidate(data.u,data.feedback);
runtimeBits=typecast(oldRuntime(:),'uint64')~=typecast(newRuntime(:),'uint64');
wordBits=oldWords~=newWords;
assert(~any(runtimeBits),'Deferred output log differs from original Runtime41 bits.');
assert(~any(wordBits,'all'),'Candidate bridge changed AXI register words.');
actual=fullfile(out,'candidate_output.bin');
f=fopen(actual,'w','ieee-le');c=onCleanup(@()fclose(f));count=fwrite(f,newRuntime','double');clear c
assert(count==numel(newRuntime));
numericOut=fullfile(out,'runtime_numeric');
command=sprintf('python "%s" --metadata "%s" --reference "%s" --actual "%s" --origin HOST --output "%s"', ...
 fullfile(root,'scripts','ax02a_compare_replay.py'), ...
 fullfile(root,'.runtime','ax02a','replay','current_motion','metadata.json'), ...
 fullfile(root,'.runtime','ax02a','replay','current_motion','reference.bin'),actual,numericOut);
[code,message]=system(command);disp(message);assert(code==0,'Original Runtime numeric comparison failed.');
numeric=jsondecode(fileread(fullfile(numericOut,'summary.json')));
result=struct('status','RUNTIME_BRIDGE_EQUIVALENCE_PASS','origin','HOST', ...
 'frames',size(newRuntime,1),'runtime_steps_per_variant',size(newRuntime,1), ...
 'runtime_bit_comparisons',numel(newRuntime),'runtime_bit_mismatches',nnz(runtimeBits), ...
 'word_comparisons',numel(newWords),'word_mismatches',nnz(wordBits), ...
 'original_runtime_numeric_failures',numeric.numerical_failures, ...
 'floating_compile_options','-O2 -fno-fast-math -ffp-contract=off', ...
 'baseline_api',baselineApi,'candidate_api',fullfile(root,'integration','ax02c2_adapter','ax02c2_adapter_api.c'), ...
 'frozen_runtime',runtime,'frozen_adapter',adapter,'candidate_output',actual, ...
 'baseline_order','Runtime step -> full41 log -> full bridge copy -> adapter/pack', ...
 'candidate_order','Runtime step -> selected bridge copy -> adapter/pack -> full41 log before next step', ...
 'adapter_scene_word_checks',adapterResult.current_motion_word_checks, ...
 'adapter_semantic_word_checks',adapterResult.semantic_word_checks, ...
 'board','NOT_RUN','target_timing','NOT_MEASURED_OFFLINE_NUMERIC_ONLY');
f=fopen(fullfile(out,'result.json'),'w');c=onCleanup(@()fclose(f));fprintf(f,'%s\n',jsonencode(result,PrettyPrint=true));
disp(result);
end
