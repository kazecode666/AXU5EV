function result=axu5ev_run_summary(out)
%% 直接读取闭环记录
c=axu5ev_matrix(out.r5_commit);
x=double(out.logsout.get('x_mm').Values.Data);
v=double(out.logsout.get('v_mmps').Values.Data);
ready=find(c(:,31)>0,1);
first_ready_s=NaN;if ~isempty(ready),first_ready_s=out.r5_commit.Time(ready);end
result=struct('stop_s',out.r5_commit.Time(end),'final_x_mm',x(end), ...
 'min_x_mm',min(x(:)),'max_x_mm',max(x(:)),'peak_v_mmps',max(abs(v(:))), ...
 'x_ref_mm',c(end,13),'accepted_target_mm',c(end,24),'Busy',c(end,25), ...
 'Ready',c(end,31),'status',c(end,27),'accepted',c(end,32),'rejected',c(end,33), ...
 'segment_id',c(end,34),'interrupted',c(end,36),'first_ready_s',first_ready_s);
assert(all(isfinite(c),'all')&&all(isfinite(x),'all')&&all(isfinite(v),'all'), ...
 'AXU5EV:FINITE','闭环记录出现非有限值。');
end
